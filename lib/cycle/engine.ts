export type EmailContent = {
  subject: string; // max 45 chars
  preheader: string; // max 90 chars
  body: string; // plain text, max 120 words, short paragraphs. Question buttons are rendered by the template.
};

/** A one-click question. Every option has the reply shown right after the click. */
export type QuestionSpec = {
  id: string; // "progress" | "goal" | "frequency" | "adaptive_w3" | "followup_w3_1" ...
  kind: "goal" | "frequency" | "progress" | "adaptive" | "followup";
  question: string;
  type: "scale" | "choice";
  options: { label: string; instantReply: string; usesPerDay?: number }[]; // scale = exactly 5 options "1".."5"
  /** Scale questions only: what 1 and 5 mean (shown next to the numbers). */
  scaleLabels?: { low: string; high: string };
};

export type StockEstimate = {
  productId: string;
  totalUnits: number; // e.g. 60
  unit: string; // e.g. "capsules"
  unitsPerUse: number; // e.g. 2
  defaultUsesPerDay: number; // from product page, e.g. 1 (used for non-primary items: no question asked)
  confidence: "high" | "medium" | "low";
};

/** "How to use your products" — sent in the welcome email, before any answer. */
export type UsageGuide = {
  items: {
    productId: string;
    title: string; // product title
    steps: string[]; // 2–3 short lines: when, how, how much
    source: "product_page" | "general" | "habit"; // where the advice comes from (see SOURCE RULES)
  }[];
  /** How to use the products together (order, timing). null for single-product orders or when no source supports it. */
  together: string | null;
};

export type OnboardingOutput = {
  niche: Niche; // niche of the primary product
  stockEstimates: StockEstimate[]; // one per order item
  usageGuide: UsageGuide;
  goalQuestion: QuestionSpec; // kind "goal" — asked in the welcome email (about the primary product)
  frequencyQuestion: QuestionSpec; // kind "frequency" — options carry usesPerDay; shown on the page after the goal click
  welcomeEmail: EmailContent; // short intro; the usage guide and the question buttons are rendered by the template
};

/** Agent 1 — decides, does not write the email. */
export type AnalystDecision = {
  customerSummary: string; // internal, 1–2 sentences: where this customer is right now
  tipFocus: string; // what this week's tip must address, and why (from the answers)
  progressNote: string | null; // one honest sentence on the progress-question trend, or null
  adaptiveQuestion: QuestionSpec; // kind "adaptive" — goes in the email
  followUpQuestions: QuestionSpec[]; // 0–2, kind "followup" — optional, on the page after the click
  progressReplies: { option: string; instantReply: string }[] | null; // 5 replies for the fixed progress question, only in progress weeks
  recommendations: { productId: string; reason: string }[];
};

/** Agent 2 — writes. */
export type WriterOutput = {
  usageTip: { title: string; body: string };
  email: EmailContent;
};

/** What the app stores and sends for the week (assembled in code). */
export type WeeklyResult = {
  usageTip: WriterOutput["usageTip"];
  email: EmailContent;
  emailQuestions: QuestionSpec[]; // 1, or 2 in progress weeks (progress first)
  followUpQuestions: QuestionSpec[];
  progressNote: string | null;
  recommendations: { productId: string; reason: string }[];
  refill: { state: RefillState; productId: string } | null;
  showRunningLowButton: true; // the template always shows "I'm running low"
};

