/**
 * Consumption Cycle — alternative to the weekly routine (per brand: journey_mode = "cycle").
 * Works for any consumable: skincare/bodycare, haircare, supplements,
 * sports nutrition, coffee/tea, pet food.
 *
 * PHASES
 *   1. onboarding → at purchase, ONE AI call: classify niche, estimate stock for every item,
 *                   write a "how to use your products" guide for EVERY purchased product,
 *                   build the 2 fixed onboarding questions (goal + usage frequency) about the
 *                   primary product, welcome email.
 *   2. weekly     → TWO AGENTS:
 *                   a) ANALYST (smarter model): reads the whole customer history and DECIDES
 *                      what to ask, what the tip should address, which products to recommend.
 *                      Writes no email copy.
 *                   b) WRITER (cheaper model): turns the decision into the tip + email
 *                      in the brand's voice.
 *   3. refill     → same pipeline as weekly, with the refill state forced to "now".
 *
 * QUESTIONS
 *   - FIXED, decided by Malyte (same for every customer of a niche → comparable data):
 *       • onboarding: goal + usage frequency
 *       • progress question: week 1, then every 3 weeks (1, 4, 7, 10...), always the same wording
 *   - ADAPTIVE, decided by the analyst every week from previous answers.
 *   - In the email: 1 question (2 in progress weeks: progress + adaptive). One click to answer.
 *   - On the page that opens after the click: 0–2 OPTIONAL follow-up questions.
 *   - Every answer option carries an instant reply shown right after the click
 *     (pre-generated by the analyst → no AI call on click, instant and cheap).
 *
 * DETERMINISTIC LOGIC IN CODE (never the model)
 *   days left, refill state ("I'm running low" button wins over the estimate),
 *   progress weeks, recommendation weeks and count, control group.
 */

