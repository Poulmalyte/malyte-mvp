// 8. SHARED CONTEXT BUILDER
// ─────────────────────────────────────────────────────────────

function nicheKeys(profiles: NicheProfiles): string {
  return Object.keys(profiles).map((k) => `"${k}"`).join(" | ");
}

function nicheBlock(p: NicheProfile): string {
  return `Goal examples: ${p.goalExamples.join("; ")}
Topics adaptive questions may explore: ${p.diaryMetrics.join("; ")}
Usage knowledge: ${p.usageKnowledge}
Usage scope: ${p.usageScope}
Fixed goal question wording: "${p.goalQuestionText ?? "What would you like to achieve with it?"}"
Fixed frequency question wording: "${p.frequencyQuestionText ?? "How often will you use it?"}"
Compliance rules:
- ${p.complianceRules.join("\n- ")}`;
}

function commonContext(input: CycleInput): string {
  const profiles = profilesOf(input);
  const niche = input.niche ? profiles[input.niche] ?? null : null;
  const nicheSection = niche
    ? `NICHE: ${niche.label}\n${nicheBlock(niche)}`
    : `NICHE: not yet classified. Classify into one of: ${Object.keys(profiles).join(", ")}, then apply that niche's settings:\n${Object.entries(
        profiles,
      )
        .map(([k, p]) => `[${k}]\n${nicheBlock(p)}`)
        .join("\n\n")}`;

  return `PHASE: ${input.phase}
LANGUAGE: ${input.language}
BRAND: ${input.brand.name}${input.brand.tone ? ` (tone: ${input.brand.tone})` : ""}

${nicheSection}

PRODUCT PURCHASED:
${JSON.stringify(input.product, null, 2)}

CATALOG (only these may be recommended):
${JSON.stringify(input.catalog, null, 2)}

CUSTOMER:
${JSON.stringify(input.customer, null, 2)}`;
}

