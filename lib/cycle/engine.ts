export type CatalogItem = {
  id: string; // Shopify product id
  title: string;
  shortDescription: string;
  size?: string; // e.g. "30 ml", "60 capsules", "1 kg"
};

export type DiaryEntry = {
  week: number;
  questionId: string; // "progress" for the fixed one, otherwise the adaptive id
  question: string;
  answer: string; // option label the customer clicked (or "1".."5")
};

export type PurchasedItem = CatalogItem & {
  productType?: string;
  tags?: string[];
  price?: string; // line price, e.g. "34.00"
  usageInstructions?: string; // "how to use" text from the product page, if the brand has one
  quantity?: number;
};

export type CycleInput = {
  phase: "onboarding" | "weekly" | "refill";
  language: string; // customer's language, e.g. "en"
  brand: { name: string; tone?: string };
  /** The PRIMARY product (see pickPrimaryProduct): questions, progress and refill are built around it. */
  product: PurchasedItem;
  /** Every product in the order (primary included). Used at onboarding for the usage guide and stock estimates. */
  orderItems?: PurchasedItem[];
  catalog: CatalogItem[]; // other products the brand sells (pre-filtered to ~15–20 relevant ones)
  customer: {
    id: string;
    firstName?: string;
    goal?: string; // answered at onboarding
    usesPerDay?: number; // answered at onboarding
    week?: number; // 1, 2, 3...
    daysLeft?: number; // computed in code
    reportedRunningLow?: boolean; // clicked "I'm running low" in any email
    diary?: DiaryEntry[]; // every answer so far, fixed + adaptive + follow-ups
    previousTips?: string[]; // to avoid repeats — include the onboarding usage-guide lines too
    previouslyRecommended?: string[]; // product ids already suggested, to rotate
  };
  niche?: Niche; // set after onboarding classification
  /** Niche profiles loaded from the database. Falls back to the built-in NICHE_PROFILES. */
  profiles?: NicheProfiles;
};

function profilesOf(input: CycleInput): NicheProfiles {
  return input.profiles && Object.keys(input.profiles).length ? input.profiles : NICHE_PROFILES;
}

