export type RefillState = "none" | "soon" | "now";

export type WeekPlan = {
  progressWeek: boolean;
  recommendationCount: number; // 0 when it's not a recommendation week
  refillState: RefillState;
};

/**
 * The primary product of an order = the one with the highest line price (ties → first in the order).
 * Questions, progress and refill are built around it; other items get the usage guide and a stock
 * estimate from their product page. (Phase 2: per-item refill reminders.)
 */
export function pickPrimaryProduct(items: PurchasedItem[]): PurchasedItem {
  if (items.length === 0) throw new Error("Order has no items.");
  const price = (i: PurchasedItem) => {
    const n = parseFloat((i.price ?? "").replace(",", "."));
    return Number.isFinite(n) ? n * (i.quantity ?? 1) : -1;
  };
  return items.reduce((best, i) => (price(i) > price(best) ? i : best), items[0]);
}

/** Safety net for the usage guide: keep only order items, in order, max 3 lines each. */
export function sanitizeUsageGuide(guide: UsageGuide, items: PurchasedItem[]): UsageGuide {
  const ids = new Set(items.map((i) => i.id));
  return {
    items: guide.items
      .filter((g) => ids.has(g.productId))
      .map((g) => ({ ...g, steps: g.steps.slice(0, 3) })),
    together: items.length > 1 ? guide.together : null,
  };
}

/** Fixed progress question: week 1, then every 3 weeks (1, 4, 7, 10...). */
export function isProgressWeek(week: number): boolean {
  return week >= 1 && (week - 1) % 3 === 0;
}

/** A new set of recommendations every 2 weeks: weeks 2, 4, 6... */
export function isRecommendationWeek(week: number): boolean {
  return week >= 2 && week % 2 === 0;
}

/**
 * How many products to recommend:
 * 0 available besides the purchased one → 0 · 1 available → 1 · 2 or more → all of them, capped at 4.
 */
export function getRecommendationCount(catalog: CatalogItem[], purchased: CatalogItem): number {
  const available = catalog.filter((p) => p.id !== purchased.id).length;
  return Math.min(available, 4);
}

export function computeDaysLeft(params: {
  totalUnits: number;
  unitsPerUse: number;
  usesPerDay: number;
  daysSincePurchase: number;
}): number {
  const dailyUse = params.unitsPerUse * params.usesPerDay;
  if (dailyUse <= 0) return Infinity;
  const used = dailyUse * params.daysSincePurchase;
  return Math.max(0, Math.round((params.totalUnits - used) / dailyUse));
}

/** "I'm running low" (customer click) always wins over the estimate. */
export function getRefillState(params: { daysLeft?: number; reportedRunningLow?: boolean; phase: CycleInput["phase"] }): RefillState {
  if (params.phase === "refill" || params.reportedRunningLow) return "now";
  const d = params.daysLeft;
  if (d === undefined || !Number.isFinite(d)) return "none";
  if (d <= 3) return "now";
  if (d <= 10) return "soon";
  return "none";
}

export function buildWeekPlan(input: CycleInput): WeekPlan {
  const week = input.customer.week ?? 1;
  return {
    progressWeek: isProgressWeek(week),
    recommendationCount: isRecommendationWeek(week) ? getRecommendationCount(input.catalog, input.product) : 0,
    refillState: getRefillState({
      daysLeft: input.customer.daysLeft,
      reportedRunningLow: input.customer.reportedRunningLow,
      phase: input.phase,
    }),
  };
}

/**
 * Control group: a stable ~pct% of each brand's customers receive NO cycle emails.
 * Comparing their repeat-purchase rate with everyone else's is the proof of Malyte's impact.
 */
export function isInControlGroup(merchantId: string, customerId: string, pct = 10): boolean {
  let h = 0x811c9dc5; // FNV-1a
  for (const ch of `${merchantId}:${customerId}`) {
    h ^= ch.charCodeAt(0);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h % 100 < pct;
}

/** Safety net: drop ids not in the catalog or equal to the purchased product, dedupe, cap. */
export function sanitizeRecommendations(
  recs: AnalystDecision["recommendations"],
  catalog: CatalogItem[],
  purchased: CatalogItem,
  max: number,
): AnalystDecision["recommendations"] {
  const validIds = new Set(catalog.map((p) => p.id));
  const seen = new Set<string>();
  return recs
    .filter((r) => validIds.has(r.productId) && r.productId !== purchased.id)
    .filter((r) => (seen.has(r.productId) ? false : (seen.add(r.productId), true)))
    .slice(0, max);
}

/** Builds the fixed progress question with the analyst's instant replies (wording never changes). */
export function buildProgressQuestion(
  niche: Niche,
  replies: AnalystDecision["progressReplies"],
  profiles: NicheProfiles = NICHE_PROFILES,
): QuestionSpec {
  const p = (profiles[niche] ?? NICHE_PROFILES[niche] ?? Object.values(NICHE_PROFILES)[0]).progressQuestion;
  return {
    id: "progress",
    kind: "progress",
    question: p.question,
    type: "scale",
    scaleLabels: { low: p.lowLabel, high: p.highLabel },
    options: ["1", "2", "3", "4", "5"].map((n) => ({
      label: n,
      instantReply: replies?.find((r) => r.option === n)?.instantReply ?? "Thanks, noted.",
    })),
  };
}

